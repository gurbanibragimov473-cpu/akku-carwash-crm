let language = localStorage.getItem("akku-language") || "en";
const originalText = new WeakMap(), originalAttributes = new WeakMap();
function translateText(value) {
  if (language !== "en") return value;
  if (translations[value]) return translations[value];
  let result = value;
  for (const [ru, en] of Object.entries(translations)) {
    if (ru.length > 7 && result.includes(ru)) result = result.replaceAll(ru, en);
  }
  return result;
}
function translatePage() {
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node), trimmed = source.trim();
    const translated = translateText(trimmed);
    if (translated !== trimmed) node.nodeValue = source.replace(trimmed, translated);
    else if (node.nodeValue !== source && language === "ru") node.nodeValue = source;
  }
  document.querySelectorAll("input, textarea, [title], [aria-label]").forEach(el => {
    let original = originalAttributes.get(el);
    if (!original) { original = {}; originalAttributes.set(el, original); }
    for (const attr of ["placeholder", "title", "aria-label"]) {
      const value = el.getAttribute(attr);
      if (value && original[attr] === undefined) original[attr] = value;
      if (original[attr]) el.setAttribute(attr, language === "en" ? (attrTranslations[original[attr]] || translateText(original[attr])) : original[attr]);
    }
  });
  document.title = language === "en" ? "AKKU — Car Wash Complex" : "АККУ — Автомоечный Комплекс";
  document.querySelectorAll("[data-language]").forEach(el => el.value = language);
  if (!document.querySelector("#language-styles")) {
    const style = document.createElement("style");
    style.id = "language-styles";
    style.textContent = ".language-select{min-height:36px;padding:0 10px;border:1px solid #dfe7e2;border-radius:9px;background:#fff;color:#34473d;font:600 12px Manrope,Arial;cursor:pointer}.language-login{align-self:flex-end;margin:-7px 0 2px}.language-header{margin-right:4px}.language-booking{display:block;margin:0 0 16px auto}.language-floating{position:fixed;top:16px;right:16px;z-index:9999}";
    document.head.append(style);
  }
}function setLanguage(next) {
  language = next;
  localStorage.setItem("akku-language", language);
  translatePage();
}
function makeLanguageControl(className) {
  const select = document.createElement("select");
  select.className = "language-select " + className;
  select.setAttribute("aria-label", "Language");
  select.setAttribute("data-language", "");
  select.innerHTML = '<option value="en">English</option><option value="ru">Русский</option>';
  select.value = language;
  select.addEventListener("change", () => setLanguage(select.value));
  return select;
}
function mountLanguageControls() {
  const loginForm = document.querySelector("#login-dialog form");
  if (loginForm && !loginForm.querySelector(".language-select")) {
    loginForm.prepend(makeLanguageControl("language-login"));
  }
  const header = document.querySelector(".header-actions");
  if (header && !header.querySelector(".language-select")) {
    header.prepend(makeLanguageControl("language-header"));
  }
  const bookingForm = document.querySelector("#booking");
  const booking = bookingForm?.parentElement;
  if (booking && !booking.querySelector(".language-select")) {
    booking.prepend(makeLanguageControl("language-booking"));
  }
  if (!loginForm && !header && !booking && !document.querySelector(".language-select")) {
    const control = makeLanguageControl("language-floating");
    control.style.cssText = "padding:9px;border:1px solid #dbe3df;border-radius:9px;background:#fff;color:#25352c;font:600 12px Manrope,Arial";
    document.body.append(control);
  }
}
document.addEventListener("DOMContentLoaded", () => {
  mountLanguageControls();
  translatePage();
  // Re-translate newly rendered app views. Do not observe characterData:
  // translatePage updates text nodes and would otherwise trigger itself forever.
  new MutationObserver(() => { mountLanguageControls(); translatePage(); }).observe(document.body, {childList:true,subtree:true});
});
